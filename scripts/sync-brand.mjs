import { spawnSync } from 'node:child_process'
import { createRequire } from 'node:module'
import { mkdtemp, readdir, readFile, mkdir, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { equalNativePixels } from './brand-raster.mjs'
import { createPublicBrandArchive } from './brand-archive.mjs'

// SVGs and palette.json in the approved kit own the identity. Consumers are
// copied/generated here; --check compares without changing the checkout.
const root = dirname(dirname(fileURLToPath(import.meta.url)))
const kit = join(root, 'design/brand/envarium-v1')
const check = process.argv.includes('--check')
const require = createRequire(join(root, 'site/package.json'))
const sharp = require('sharp')
const drift = []
let count = 0

async function emit(target, data, nativePNG = false) {
  const bytes = Buffer.isBuffer(data) ? data : Buffer.from(data)
  const destination = join(root, target)
  const previous = await readFile(destination).catch((error) => {
    if (error.code !== 'ENOENT') throw error
    return undefined
  })
  count++
  if (previous?.equals(bytes)) return
  if (check && previous && nativePNG) {
    const [left, right] = await Promise.all(
      [previous, bytes].map((input) =>
        sharp(input).ensureAlpha().raw().toBuffer({ resolveWithObject: true }),
      ),
    )
    if (
      left.info.width === right.info.width &&
      left.info.height === right.info.height &&
      left.info.channels === right.info.channels &&
      equalNativePixels(left.data, right.data)
    )
      return
  }
  if (check) drift.push(target)
  else {
    await mkdir(dirname(destination), { recursive: true })
    await writeFile(destination, bytes)
  }
}

async function copy(source, target) {
  await emit(target, await readFile(join(kit, source)))
}

function canonicalICNS(bytes) {
  // Tauri's ICNS encoder iterates a hash map; entry order is not stable.
  // Sort the independent image chunks so byte comparisons work in CI.
  const chunks = []
  for (let offset = 8; offset < bytes.length;) {
    const size = bytes.readUInt32BE(offset + 4)
    if (size < 8 || offset + size > bytes.length) throw new Error('Invalid ICNS entry')
    chunks.push(bytes.subarray(offset, offset + size))
    offset += size
  }
  chunks.sort((left, right) => Buffer.compare(left.subarray(0, 4), right.subarray(0, 4)))
  return Buffer.concat([bytes.subarray(0, 8), ...chunks])
}

async function filesUnder(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  return (
    await Promise.all(
      entries.map((entry) => {
        const file = join(directory, entry.name)
        return entry.isDirectory() ? filesUnder(file) : [file]
      }),
    )
  )
    .flat()
    .sort()
}

const palette = JSON.parse(await readFile(join(kit, 'palette.json'), 'utf8'))
const css = `/* Generated by scripts/sync-brand.mjs from the approved brand palette. */\n:root {\n${Object.entries(
  palette,
)
  .map(([name, value]) => `  --brand-${name}: ${value};`)
  .join(
    '\n',
  )}\n  --brand-gradient: linear-gradient(135deg, var(--brand-blue), var(--brand-violet));\n}\n`
for (const target of [
  'web/src/styles/brand.css',
  'site/src/styles/brand.css',
  'desktop/ui/brand.css',
])
  await emit(target, css)

const iconFiles = (await filesUnder(join(kit, 'interface'))).filter((file) => file.endsWith('.svg'))
const symbols = await Promise.all(
  iconFiles.map(async (file) => {
    const name = relative(join(kit, 'interface'), file).replace('.svg', '')
    const content = (await readFile(file, 'utf8'))
      .replace(/^<svg[^>]*>/, '')
      .replace(/<\/svg>\s*$/, '')
    return `<symbol id="${name}" viewBox="0 0 24 24">${content}</symbol>`
  }),
)
const sprite = `<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${symbols.join('')}</svg>\n`
for (const target of ['web/public/brand/interface.svg', 'site/public/brand/interface.svg'])
  await emit(target, sprite)

for (const directory of ['logos', 'marks', 'interface', 'app', 'web', 'tray']) {
  for (const file of await filesUnder(join(kit, directory)))
    await copy(relative(kit, file), `site/public/brand/${relative(kit, file)}`)
}
await copy('preview.png', 'site/public/brand/preview.png')
await copy('README.md', 'site/public/brand/README.md')
const license = await readFile(join(root, 'LICENSE'))
const notice = await readFile(join(root, 'NOTICE'))
const archive = await createPublicBrandArchive(kit, license, notice)
await emit('design/brand/envarium-v1.zip', archive)
await emit('site/public/brand/envarium-brand-kit.zip', archive)
await emit('site/public/brand/LICENSE', license)
await emit('site/public/brand/NOTICE', notice)
for (const [source, target] of [
  ['marks/envarium-gradient.svg', 'web/public/envarium-icon.svg'],
  ['marks/envarium-gradient.svg', 'web/public/brand/mark.svg'],
  ['marks/envarium-white.svg', 'web/public/brand/mark-contrast.svg'],
  ['logos/envarium-on-dark.svg', 'web/public/brand/logo.svg'],
  ['logos/envarium-white.svg', 'web/public/brand/logo-contrast.svg'],
  ['app/envarium-app.svg', 'desktop/icon.svg'],
  ['marks/envarium-gradient.svg', 'desktop/ui/icon.svg'],
  ['web/favicon.svg', 'site/public/favicon.svg'],
  ['web/favicon.svg', 'web/public/favicon.svg'],
  ['web/favicon.ico', 'site/public/favicon.ico'],
  ['web/favicon.ico', 'web/public/favicon.ico'],
])
  await copy(source, target)
for (const consumer of ['web', 'site'])
  for (const size of [180, 192, 512])
    await copy(`web/envarium-${size}.png`, `${consumer}/public/envarium-${size}.png`)

// Generate every platform's icon using the project's pinned Tauri CLI, in a
// temporary directory so --check is safe and failed generation changes nothing.
const temporary = await mkdtemp(join(tmpdir(), 'envarium-brand-'))
try {
  const native = join(temporary, 'icons')
  const result = spawnSync(
    process.execPath,
    [
      join(root, 'node_modules/@tauri-apps/cli/tauri.js'),
      'icon',
      join(kit, 'app/envarium-app.svg'),
      '--output',
      native,
      '--ios-color',
      palette.canvas,
    ],
    { encoding: 'utf8' },
  )
  if (result.status !== 0)
    throw new Error(result.stderr || result.error?.message || 'Tauri icon generation failed')
  for (const file of await filesUnder(native)) {
    const bytes = await readFile(file)
    await emit(
      `desktop/src-tauri/icons/${relative(native, file)}`,
      file.endsWith('.icns') ? canonicalICNS(bytes) : bytes,
      file.endsWith('.png'),
    )
  }
  const template = await sharp(join(kit, 'tray/envarium-dark-32.png'))
    .ensureAlpha()
    .raw()
    .toBuffer()
  await emit('desktop/src-tauri/icons/tray-icon.rgba', template)
} finally {
  await rm(temporary, { recursive: true, force: true })
}

const social = await readFile(join(kit, 'social.svg'))
await emit('site/public/social/default.svg', social)
await emit('site/public/social/default.png', await sharp(social).png().toBuffer())
if (drift.length)
  throw new Error(`Brand assets are stale. Run pnpm brand:sync:\n${drift.join('\n')}`)
console.log(`${check ? 'Checked' : 'Synced'} ${count} brand assets and palette consumers.`)
